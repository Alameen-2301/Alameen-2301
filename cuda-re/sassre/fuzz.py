"""Bit-flip field discovery.

For every distinct instruction *form* in the corpus (opcode + operand-type
bits 0..11), take one real encoding, flip each of the 128 bits on its own,
and ask nvdisasm what changed. Every bit is classified as:

    illegal      encoding rejected  -> part of the opcode / a reserved value
    opcode       the mnemonic changed (e.g. FADD -> FMUL)
    mod          same base mnemonic, different .MODIFIER
    op<N>        operand N changed (op0 = first operand)
    guard        the @P predicate guard changed
    reuse        an operand gained/lost a .reuse flag (operand reuse cache)
    -            no visible change (control/scheduling bits, unused bits)

Contiguous bits with the same class are merged into fields.

    python -m sassre.fuzz [sm_80]  -> data/fields_<arch>.json + docs/fields_<arch>.md
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict

from .corpus import load, mnemonic
from .toolchain import ROOT, disasm_raw

FORM_MASK = 0xFFF
YIELD_BIT = 1 << (109 - 64)


def split_ops(text: str) -> tuple[str, str, list[str]]:
    """'@!P0 FADD.FTZ R1, R2, -R3' -> ('@!P0', 'FADD.FTZ', ['R1','R2','-R3'])"""
    t = text.strip()
    guard = ""
    if t.startswith("@"):
        guard, t = t.split(None, 1)
    parts = t.split(None, 1)
    mn = parts[0]
    ops = []
    if len(parts) > 1:
        depth, cur = 0, ""
        for ch in parts[1]:
            if ch in "[{(":
                depth += 1
            elif ch in "]})":
                depth -= 1
            if ch == "," and depth == 0:
                ops.append(cur.strip())
                cur = ""
            else:
                cur += ch
        if cur.strip():
            ops.append(cur.strip())
    return guard, mn, ops


def classify(base: str, new: str | None) -> tuple[str, str]:
    if new is None:
        return "illegal", ""
    if new == base:
        return "-", ""
    g0, m0, o0 = split_ops(base)
    g1, m1, o1 = split_ops(new)
    if m0 != m1:
        if m0.split(".")[0] != m1.split(".")[0]:
            return "opcode", m1
        return "mod", m1
    if g0 != g1:
        return "guard", g1 or "(none)"
    if len(o0) != len(o1):
        return "mod", new
    diffs = [i for i, (a, b) in enumerate(zip(o0, o1)) if a != b]
    if all(o1[i].replace(".reuse", "") == o0[i].replace(".reuse", "") for i in diffs):
        return "reuse", f"op{diffs[0]}"
    if len(diffs) == 1:
        return f"op{diffs[0]}", o1[diffs[0]]
    return "op" + "+".join(map(str, diffs)), new


def seeds(arch: str) -> dict[int, tuple[int, int, str]]:
    """One representative encoding per form. Prefer unpredicated instructions
    with no .reuse so that guard/reuse bits flip *on* and are visible."""
    best: dict[int, tuple[int, int, str]] = {}
    for lo, hi, t in load(arch):
        f = lo & FORM_MASK
        score = (t.startswith("@"), ".reuse" in t, len(t))
        if f not in best or score < best[f][3]:
            best[f] = (lo, hi, t, score)
    return {f: v[:3] for f, v in best.items()}


def run(arch: str = "sm_80") -> dict:
    sd = seeds(arch)
    # nvdisasm only prints .reuse when control bit 109 is set, so set it in
    # each seed where that stays legal (bit 109 + stall >= 13 is rejected).
    keys = list(sd)
    tries = disasm_raw([(sd[f][0], sd[f][1] | YIELD_BIT) for f in keys], arch)
    sd = {f: (sd[f][0], sd[f][1] | (YIELD_BIT if ok == sd[f][2] else 0), sd[f][2])
          for f, ok in zip(keys, tries)}
    words, index = [], []
    for f, (lo, hi, _) in sd.items():
        for b in range(128):
            words.append((lo ^ (1 << b), hi) if b < 64 else (lo, hi ^ (1 << (b - 64))))
            index.append((f, b))
    texts: list[str | None] = []
    CH = 4096
    for i in range(0, len(words), CH):
        texts += disasm_raw(words[i:i + CH], arch)
        print(f"  {min(i + CH, len(words))}/{len(words)}", file=sys.stderr)

    per = defaultdict(list)
    for (f, b), t in zip(index, texts):
        per[f].append((b, *classify(sd[f][2], t)))

    out = {}
    for f, bits in per.items():
        lo, hi, t = sd[f]
        fields, cur = [], None
        for b, cls, ex in sorted(bits):
            if cur and cur["class"] == cls and cur["hi"] == b - 1:
                cur["hi"] = b
                if ex and len(cur["examples"]) < 3 and ex not in cur["examples"]:
                    cur["examples"].append(ex)
            else:
                cur = {"lo": b, "hi": b, "class": cls, "examples": [ex] if ex else []}
                fields.append(cur)
        out[f"{f:03x}"] = {"mnemonic": mnemonic(t), "seed": t,
                           "enc": f"{hi:016x}{lo:016x}", "fields": fields}
    return out


def report(arch: str, res: dict) -> str:
    L = [f"# SASS field map — {arch}",
         "",
         "Generated by `python -m sassre.fuzz` (bit-flip against nvdisasm). "
         "Bit 0 = LSB of the low 64-bit word; bits 64–127 are the high word.",
         "`-` = no visible change (scheduling/control or unused). ",
         ""]
    for f, r in sorted(res.items(), key=lambda kv: (kv[1]["mnemonic"], kv[0])):
        L.append(f"## `{r['mnemonic']}` form 0x{f} — `{r['seed']}`")
        L.append(f"`0x{r['enc']}`\n")
        L.append("| bits | class | examples |")
        L.append("|---|---|---|")
        for fd in r["fields"]:
            rng = f"{fd['lo']}" if fd["lo"] == fd["hi"] else f"{fd['lo']}–{fd['hi']}"
            ex = ", ".join(f"`{e}`" for e in fd["examples"])
            L.append(f"| {rng} | {fd['class']} | {ex} |")
        L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    arch = sys.argv[1] if len(sys.argv) > 1 else "sm_80"
    res = run(arch)
    (ROOT / "data" / f"fields_{arch}.json").write_text(json.dumps(res, indent=1))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / f"fields_{arch}.md").write_text(report(arch, res))
    print(f"{len(res)} forms mapped -> data/fields_{arch}.json, docs/fields_{arch}.md")
